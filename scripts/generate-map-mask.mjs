import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const root = path.resolve(__dirname, '..');

const inputPath = process.argv[2];
const outputPath = path.join(root, 'src', 'game', 'maps', 'infernoWalkable.ts');
const width = 90;
const height = 100;
const threshold = Number(process.argv[3] || 85);

if (!inputPath) {
  console.error('Usage: node scripts/generate-map-mask.mjs <radar.png> [luminance-threshold]');
  console.error('Example: node scripts/generate-map-mask.mjs C:\\path\\to\\de_inferno_radar.png 85');
  process.exit(1);
}

function getLuminance(r, g, b) {
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function sampleTile(image, tx, ty) {
  const x0 = Math.floor((tx * image.width) / width);
  const x1 = Math.floor(((tx + 1) * image.width) / width);

  // Game-space y=0 is the bottom of the radar, so invert image y.
  const y0 = Math.floor(((height - 1 - ty) * image.height) / height);
  const y1 = Math.floor(((height - ty) * image.height) / height);

  let luminance = 0;
  let count = 0;

  for (let y = y0; y < y1; y++) {
    for (let x = x0; x < x1; x++) {
      const i = (y * image.width + x) * 4;
      const alpha = image.data[i + 3];
      if (alpha < 10) continue;

      luminance += getLuminance(image.data[i], image.data[i + 1], image.data[i + 2]);
      count++;
    }
  }

  return count === 0 ? 0 : luminance / count;
}

function generateMask(image) {
  const rows = [];

  for (let y = 0; y < height; y++) {
    let row = '';
    for (let x = 0; x < width; x++) {
      row += sampleTile(image, x, y) >= threshold ? '1' : '0';
    }
    rows.push(row);
  }

  return rows;
}

function pruneToLargestComponent(mask) {
  const dirs = [
    [1, 0],
    [-1, 0],
    [0, 1],
    [0, -1],
  ];
  const key = (x, y) => `${x},${y}`;
  const seen = new Set();
  const components = [];

  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const startKey = key(x, y);
      if (mask[y][x] !== '1' || seen.has(startKey)) continue;

      const queue = [{ x, y }];
      const component = [];
      seen.add(startKey);

      while (queue.length > 0) {
        const current = queue.shift();
        component.push(current);

        for (const [dx, dy] of dirs) {
          const nx = current.x + dx;
          const ny = current.y + dy;
          const nextKey = key(nx, ny);
          if (nx < 0 || ny < 0 || nx >= width || ny >= height) continue;
          if (seen.has(nextKey) || mask[ny][nx] !== '1') continue;

          seen.add(nextKey);
          queue.push({ x: nx, y: ny });
        }
      }

      components.push(component);
    }
  }

  const largest = components.sort((a, b) => b.length - a.length)[0] || [];
  const keep = new Set(largest.map((tile) => key(tile.x, tile.y)));

  return mask.map((row, y) =>
    row
      .split('')
      .map((value, x) => (value === '1' && keep.has(key(x, y)) ? '1' : '0'))
      .join('')
  );
}

function writeMask(mask) {
  const file = `// Generated by scripts/generate-map-mask.mjs.
// Source image is intentionally not committed. Regenerate from a local
// de_inferno_radar.png-style top-down reference when rebuilding the map.
//
// Coordinate convention:
// - 90 columns x 100 rows
// - row 0 is the T-side/bottom side of the radar
// - "1" means walkable floor, "0" means wall/outside mass

export const INFERNO_WALKABLE_MASK = [
${mask.map((row) => `  '${row}',`).join('\n')}
] as const;
`;

  fs.writeFileSync(outputPath, file);
}

const image = PNG.sync.read(fs.readFileSync(inputPath));
const rawMask = generateMask(image);
const mask = pruneToLargestComponent(rawMask);
writeMask(mask);

const walkable = mask.join('').split('').filter((value) => value === '1').length;
console.log(JSON.stringify({
  input: inputPath,
  output: path.relative(root, outputPath),
  width,
  height,
  threshold,
  walkableTiles: walkable,
  walkablePercent: Number(((walkable / (width * height)) * 100).toFixed(1)),
}, null, 2));
